  study: `Topic at a glance
Section 18 of the Bharatiya Nyaya Sanhita, 2023 (Act 45 of 2023) codifies the defence of unavoidable accident and misfortune. The bedrock principle of criminal jurisprudence — actus non facit reum nisi mens sit rea — dictates that unintended, unforeseen, and non-negligent harm resulting from innocent human conduct cannot be visited with penal sanctions.

Statutory Text (Section 18 BNS)
"Nothing is an offence which is done by accident or misfortune, and without any criminal intention or knowledge in the doing of a lawful act in a lawful manner by lawful means and with proper care and caution."

Statutory Illustration
"A is at work with a hatchet; the head flies off and kills a man who is standing by. Here, if there was no want of proper care and caution on the part of A, his act is excusable and not an offence."

The Five Cumulative Ingredients of Section 18
To successfully invoke the exception of accident under Section 18, all five statutory conditions must coexist simultaneously:
1. Occurrence by Accident or Misfortune: An event that happens unexpectedly, without design, and beyond ordinary human foresight.
2. Absence of Criminal Intent or Knowledge: The actor must have had zero mens rea — neither an intention to cause harm nor knowledge that the act was likely to cause harm.
3. Lawfulness of the Act: The underlying activity must be completely lawful under civil and penal law. If a person is engaged in an unlawful act (e.g., shooting an unlicensed firearm, committing burglary), the defence of accident is strictly unavailable.
4. Lawful Manner and Means: Both the method of execution and the instruments employed must be permitted by law.
5. Proper Care and Caution: The actor must have exercised that degree of care, vigilance, and caution which an ordinarily prudent and reasonable person would exercise in the circumstances.

Accident vs Criminal Rashness / Negligence (Section 106 BNS)
The critical courtroom battleground lies between Section 18 BNS (pure accident = complete acquittal) and Section 106 BNS (causing death by rash or negligent act = punishable with imprisonment).
• In an accident, proper care and caution was present, and the consequence was an unforeseeable calamity.
• In criminal negligence, there is a breach of a positive duty of care (gross carelessness).
• In criminal rashness, the actor foresees the hazard but recklessly gambles that the risk will not materialize.`,

