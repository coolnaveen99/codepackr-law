  study: `Topic at a glance
Section 21 of the Bharatiya Nyaya Sanhita, 2023 (Act 45 of 2023) governs the transitional developmental period between early infancy (under seven) and adolescent responsibility. While Section 20 confers an absolute immunity (doli incapax), Section 21 provides a qualified, rebuttable immunity for children between seven and twelve years of age.

Statutory Text (Section 21 BNS)
"Nothing is an offence which is done by a child above seven years of age and under twelve, who has not attained sufficient maturity of understanding to judge of the nature and consequences of his conduct on that occasion."

The Doctrine: "Malitia Supplet Aetatem" (Malice Supplies Age)
At common law and under the Sanhita, a child between 7 and 12 is prima facie presumed to be doli incapax. However, this presumption is rebuttable ("praesumptio juris tantum"). The prosecution can overturn this presumption by establishing that the child possessed "sufficient maturity of understanding" to comprehend the physical nature and natural consequences of what he was doing on that specific occasion. If malice or intelligent design is proved, "malice supplies age".

Deconstruction of "Nature and Consequences of Conduct"
The word "consequences" in Section 21 does not denote legal consequences (such as understanding that the act violates Section 103 BNS or leads to prison). It denotes the physical, natural, and immediate consequences of the act:
• Knowing that plunging a sharp knife into someone's chest will cause severe bleeding and death.
• Knowing that setting fire to a thatched roof will incinerate the house.
• Knowing that taking a gold ring and hiding it in a bush deprives the owner of his property.

The Crucial Temporal Anchor: "On That Occasion"
Maturity is not judged as an abstract, general intelligence quotient. Section 21 explicitly confines the judicial inquiry to the child's capacity "on that occasion". A child may be generally playful or slow, but if the evidence demonstrates cunning, stealth, premeditation, hiding the weapon, or fabricating an alibi on that specific occasion, sufficient maturity is judicially established.

Interplay with the Juvenile Justice Act, 2015
Even if a child between 7 and 12 is found to possess sufficient maturity of understanding (thereby forfeiting Section 21 immunity), he CANNOT be tried by an ordinary criminal court or sentenced to prison. The child must be dealt with exclusively by the Juvenile Justice Board (JJB) under the Juvenile Justice (Care and Protection of Children) Act, 2015, focusing on counseling, community service, or placement in a special home for a maximum of three years.`,

