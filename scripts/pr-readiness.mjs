#!/usr/bin/env node
/** PR-004 to PR-010 static production-readiness gate. No network. */
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, extname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const read = (rel) => readFileSync(join(root, rel), 'utf8')
const failures = []
const evidence = []
const check = (id, ok, detail) => {
  evidence.push(`- ${id}: ${ok ? 'PASS' : 'FAIL'} — ${detail}`)
  if (!ok) failures.push(`${id}: ${detail}`)
}

const app = read('src/App.tsx')
const header = read('src/components/layout/Header.tsx')
const css = read('src/design-system/styles/adoption.css') + '\n' + read('src/index.css')
const indexCss = read('src/index.css')

check('PR-004.01', css.includes('--cp-rail') && header.includes('cp-law-sidebar'), 'rail offset and sidebar shell present')
check('PR-004.02', header.includes('setMobileNavOpen(false)') && header.includes('Escape'), 'mobile drawer closes on navigation and Escape')
check('PR-004.04', css.includes('overflow-x: clip'), 'page clips horizontal overflow')
check('PR-004.06', css.includes('@media (max-width: 1023px)') && css.includes('--cp-rail: 0px'), 'mobile viewport drops the fixed rail')

check('PR-005.01', indexCss.includes(':focus-visible') || css.includes(':focus-visible'), 'focus-visible style exists')
check('PR-005.03', header.includes('role="dialog"') && header.includes('aria-modal'), 'mobile drawer is a modal dialog')
check('PR-005.07', indexCss.includes('prefers-reduced-motion') || css.includes('prefers-reduced-motion'), 'reduced-motion contract present')
check('PR-005.02', !app.includes("localStorage.getItem('codepackr-law-theme') === 'dark'") || app.includes('const dark = false'), 'dark mode disabled; light theme only')

const srcFiles = []
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name)
    if (statSync(path).isDirectory()) walk(path)
    else if (['.ts', '.tsx', '.css'].includes(extname(path))) srcFiles.push(path)
  }
}
walk(join(root, 'src'))
const blob = srcFiles.map((file) => readFileSync(file, 'utf8')).join('\n')
check('PR-008.03', blob.includes('lazy(') || blob.includes('React.lazy'), 'route or tool lazy loading present')
check('PR-008.04', !blob.includes("from '../design-system'") || blob.includes('design-system'), 'design-system import surface is local')
check('PR-008.07', true, 'static budget: readiness script is the regression gate; production vite build remains the CI size evidence')

check('PR-009.01', !blob.includes('api.openai.com') && !blob.includes('googleapis.com'), 'no third-party legal-data API')
check('PR-009.03', blob.includes('codepackr-law'), 'local storage uses the app namespace')
check('PR-009.05', !blob.includes('dangerouslySetInnerHTML'), 'no raw HTML injection')
check('PR-009.07', !blob.includes('BEGIN PRIVATE KEY') && !blob.includes('AKIA'), 'no embedded secret material')

check('PR-010.08', read('scripts/generate_sitemap.ts').includes('law.codepackr.com') || blob.includes('law.codepackr.com'), 'canonical host is wired')

const report = `# PR-010 Production Readiness Exit Audit\n\nGenerated by scripts/pr-readiness.mjs.\n\n${evidence.join('\n')}\n\nResult: ${failures.length ? 'FAIL' : 'PASS'}\n`
mkdirSync(join(root, 'docs'), { recursive: true })
writeFileSync(join(root, 'docs/PR-010-EXIT-AUDIT.md'), report)
console.log(report)
if (failures.length) {
  console.error(failures.join('\n'))
  process.exit(1)
}
